"""
Convert DejaVu Sans into bitmap font modules for the ESP32.

MicroPython can't read TTF files, so this renders every printable ASCII character
on your computer and stores the pixels in Python modules (display_usage/esp32/dejavu_sans_*.py).
It uses the same font and sizes as the Raspberry Pi, so both displays show the same pixels.

Run it from the project folder (needs Pillow and DejaVuSans.ttf):

    uv run --no-project --with pillow python -B -m tools.make_esp32_fonts DejaVuSans.ttf
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

from display_usage.display import BaseDisplay


SIZES = (BaseDisplay.FONT_SIZE, BaseDisplay.SMALL_FONT_SIZE)
FIRST, LAST = 32, 126
OUTPUT_DIRECTORY = os.path.join("display_usage", "esp32")
BYTES_PER_LINE = 20
KERNING_PAIRS_PER_LINE = 25
KERNING_SHIFTS = (0, -1, -2, 1, -3, 2)
PADDING = 4  # room for glyphs that reach left of or above the drawing position


def render_glyph(font, char):
    """Return (advance, x offset, y offset, width, height, MONO_HLSB bytes) of one character."""
    advance = round(font.getlength(char))
    size = (advance + 2 * PADDING + 8, font.size * 2 + 2 * PADDING)
    image = Image.new("1", size)
    ImageDraw.Draw(image).text((PADDING, PADDING), char, font=font, fill=1)
    box = image.getbbox()
    if box is None:  # space
        return advance, 0, 0, 0, 0, b""
    glyph = image.crop(box)
    width, height = glyph.size
    data = bytearray()
    for y in range(height):
        for byte_start in range(0, width, 8):
            byte = 0
            for bit in range(8):
                x = byte_start + bit
                if x < width and glyph.getpixel((x, y)):
                    byte |= 0x80 >> bit
            data.append(byte)
    return advance, box[0] - PADDING, box[1] - PADDING, width, height, bytes(data)


def render_pixels(font, text, x=0):
    image = Image.new("1", (font.size * 4, font.size * 2 + 2 * PADDING))
    ImageDraw.Draw(image).text((x + PADDING, PADDING), text, font=font, fill=1)
    return {i for i, pixel in enumerate(image.get_flattened_data()) if pixel}


def find_kerning(font, chars):
    """Return {pair: shift} for character pairs that PIL draws closer or wider apart.

    PIL adjusts some pairs when it draws a whole string (kerning and hinting), but
    not when it measures single characters. Each pair is drawn as a whole and compared
    with the two characters drawn separately at a few shifts.
    """
    singles = {char: render_pixels(font, char) for char in chars}
    kerning = {}
    for first in chars:
        advance = round(font.getlength(first))
        for second in chars:
            whole = render_pixels(font, first + second)
            for shift in KERNING_SHIFTS:
                if singles[first] | render_pixels(font, second, advance + shift) == whole:
                    if shift:
                        kerning[first + second] = shift
                    break
    return kerning


def write_module(font_path, size):
    font = ImageFont.truetype(font_path, size)
    chars = [chr(code) for code in range(FIRST, LAST + 1)]
    glyph_lines, data = [], b""
    for char in chars:
        advance, x_offset, y_offset, width, height, glyph_data = render_glyph(font, char)
        glyph_lines.append(
            f"    ({advance}, {x_offset}, {y_offset}, {width}, {height}, {len(data)}),"
            f"  # {char!r}"
        )
        data += glyph_data

    data_lines = [
        '    b"' + "".join(f"\\x{byte:02x}" for byte in data[i : i + BYTES_PER_LINE]) + '"'
        for i in range(0, len(data), BYTES_PER_LINE)
    ]
    # Sorted 3-byte records: first char, second char, shift + 48 (so all bytes are printable).
    kerning = b"".join(
        pair.encode() + bytes([48 + shift])
        for pair, shift in sorted(find_kerning(font, chars).items())
    )
    record_size = 3 * KERNING_PAIRS_PER_LINE
    kerning_lines = [
        f"    {kerning[i : i + record_size]!r}" for i in range(0, len(kerning), record_size)
    ]
    path = os.path.join(OUTPUT_DIRECTORY, f"dejavu_sans_{size}.py")
    with open(path, "w") as handle:
        handle.write(
            f"# DejaVu Sans {size} px, generated by tools/make_esp32_fonts.py. Do not edit.\n"
            "# DejaVu fonts license: https://dejavu-fonts.github.io/License.html\n"
            "\n"
            f"FIRST = {FIRST}\n"
            "# (advance, x offset, y offset, width, height, start in DATA) per character\n"
            "GLYPHS = (\n" + "\n".join(glyph_lines) + "\n)\n"
            "DATA = (\n" + "\n".join(data_lines) + "\n)\n"
            "# (first char, second char, shift + 48) per pair, sorted\n"
            "KERNING = (\n" + "\n".join(kerning_lines) + "\n)\n"
        )
    print(f"{path}: {len(data)} bytes glyphs, {len(kerning) // 3} kerning pairs")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    for size in SIZES:
        write_module(sys.argv[1], size)
